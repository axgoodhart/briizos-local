#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const require = createRequire(import.meta.url);
const {
  BROWSE_TOOL,
  DATA_OBJECTS,
  MODALITY_SLICES,
  QUERY_DATA_DOMAINS,
  RESTRICTED_OBJECTS,
} = require(path.join(repoRoot, 'electron/agent/data-catalog.js'));

const outputPath = path.join(repoRoot, 'electron/agent/DATA-CATALOG.md');
const args = new Set(process.argv.slice(2));

function list(values) {
  return values.map((value) => `- ${value}`).join('\n');
}

function renderObject(objectDef) {
  const relationships = objectDef.relationships?.length
    ? `\nRelationships:\n${list(objectDef.relationships)}`
    : '';
  const filters = objectDef.filters?.length
    ? `\nFilters and detail controls:\n${list(objectDef.filters)}`
    : '';
  return `## ${objectDef.title}\n\n` +
    `- Key: \`${objectDef.key}\`\n` +
    `- Category: \`${objectDef.category}\`\n` +
    `- Read tools: ${objectDef.tools.map((toolName) => `\`${toolName}\``).join(', ')}\n\n` +
    `${objectDef.description}\n\n` +
    `Fields:\n${list(objectDef.fields)}` +
    `${relationships}${filters}`;
}

function renderMarkdown() {
  const modalityRows = Object.entries(MODALITY_SLICES)
    .map(([modality, keys]) => `| \`${modality}\` | ${keys.map((key) => `\`${key}\``).join(', ') || 'None'} |`)
    .join('\n');
  const restricted = RESTRICTED_OBJECTS
    .map((objectDef) => `- \`${objectDef.key}\`: ${objectDef.reason}`)
    .join('\n');

  return `# briizOS AI Data Catalog\n\n` +
    `<!-- Generated by scripts/generate-tool-catalog.mjs. Edit data-catalog.js, not this file. -->\n\n` +
    `This document mirrors \`electron/agent/data-catalog.js\`, the source of truth for data the in-process agent may read. Reads are local, read-only, and logged as \`agent.data\`. Values remain stored once; panels and calendar placements are contextual appearances.\n\n` +
    `The dedicated task, Islands, organizer, placement, and schedule tools remain optimized for common work. ` +
    `\`${BROWSE_TOOL}\` provides bounded access to these additional domains: ${QUERY_DATA_DOMAINS.map((key) => `\`${key}\``).join(', ')}.\n\n` +
    `${DATA_OBJECTS.map(renderObject).join('\n\n')}\n\n` +
    `## Modality slices\n\n| Modality | Injected objects |\n|---|---|\n${modalityRows}\n\n` +
    `## Unavailable by design\n\n${restricted}\n`;
}

const generated = renderMarkdown();

if (args.has('--stdout')) {
  process.stdout.write(generated);
} else if (args.has('--check')) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (current !== generated) {
    console.error('electron/agent/DATA-CATALOG.md is out of date. Run npm run tools:catalog.');
    process.exitCode = 1;
  } else {
    console.log('electron/agent/DATA-CATALOG.md is current.');
  }
} else {
  fs.writeFileSync(outputPath, generated);
  console.log(`Wrote ${path.relative(repoRoot, outputPath)}`);
}
